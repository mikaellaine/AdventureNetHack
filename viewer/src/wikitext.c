static int is_image_keyword(const char *s) {
    static const char *kw[] = {
        "thumb", "thumbnail", "left", "right", "center", "centre", "none",
        "frame", "framed", "frameless", "border", "upright", NULL
    };
    for (int i = 0; kw[i]; i++) if (strcasecmp(s, kw[i]) == 0) return 1;
    size_t n = strlen(s);
    if (n > 2 && strcasecmp(s + n - 2, "px") == 0) return 1;
    if (strchr(s, '=')) return 1;
    return 0;
}

static void flush_buf(SB *buf, RunList *out, unsigned attr) {
    if (buf->len > 0) {
        runlist_push(out, buf->buf, attr, -1);
        buf->len = 0;
        buf->buf[0] = '\0';
    }
}

/* Finds the "]]" that matches the "[[" already consumed before `p`, so
 * captions containing their own nested [[links]] (common on image
 * captions) aren't cut off at the first, inner "]]". Returns a pointer to
 * the start of the matching "]]", or NULL if unterminated. */
static const char *find_link_close(const char *p) {
    int depth = 1;
    while (*p) {
        if (p[0] == '[' && p[1] == '[') { depth++; p += 2; continue; }
        if (p[0] == ']' && p[1] == ']') {
            depth--;
            if (depth == 0) return p;
            p += 2;
            continue;
        }
        p++;
    }
    return NULL;
}

/* Splits `s` on top-level '|' characters, ignoring ones nested inside
 * [[ ... ]] (image captions routinely contain their own [[links]]).
 * Returns a malloc'd array of malloc'd strings; caller frees both. */
static char **depth_split_pipe(const char *s, int *out_n) {
    int cap = 8, n = 0;
    char **out = malloc(cap * sizeof(char *));
    int depth = 0;
    const char *seg = s;
    const char *p = s;
    while (*p) {
        if (p[0] == '[' && p[1] == '[') { depth++; p += 2; continue; }
        if (p[0] == ']' && p[1] == ']') { if (depth > 0) depth--; p += 2; continue; }
        if (depth == 0 && *p == '|') {
            size_t len = (size_t)(p - seg);
            char *piece = malloc(len + 1);
            memcpy(piece, seg, len);
            piece[len] = '\0';
            if (n == cap) { cap *= 2; out = realloc(out, cap * sizeof(char *)); }
            out[n++] = piece;
            p++;
            seg = p;
            continue;
        }
        p++;
    }
    size_t len = (size_t)(p - seg);
    char *piece = malloc(len + 1);
    memcpy(piece, seg, len);
    piece[len] = '\0';
    if (n == cap) { cap *= 2; out = realloc(out, cap * sizeof(char *)); }
    out[n++] = piece;
    *out_n = n;
    return out;
}

