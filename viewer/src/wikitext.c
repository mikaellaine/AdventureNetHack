    while (*p) {
        if (starts_with_ci(p, "<nowiki") || starts_with_ci(p, "</nowiki")) {
            char *gt = strchr(p, '>');
            p = gt ? gt + 1 : p + strlen(p);
            continue;
        }
        sb_putc(&out, *p);
        p++;
    }
    free(in);
