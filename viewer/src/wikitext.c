static const char *handle_internal_link(const char *p, Doc *doc, const WikiIndex *idx, RunList *out) {
    p += 2; /* skip [[ */
    const char *end = find_link_close(p);
    const char *stop = end ? end : p + strlen(p);
    size_t clen = (size_t)(stop - p);
    char content[2048];
    size_t cl = clen < sizeof(content) - 1 ? clen : sizeof(content) - 1;
    memcpy(content, p, cl);
    content[cl] = '\0';
    const char *after = end ? end + 2 : stop;

    char *pipe = strchr(content, '|');
    char target_buf[1024];
    if (pipe) {
        size_t tl = (size_t)(pipe - content);
        if (tl > sizeof(target_buf) - 1) tl = sizeof(target_buf) - 1;
        memcpy(target_buf, content, tl);
        target_buf[tl] = '\0';
    } else {
        strncpy(target_buf, content, sizeof(target_buf) - 1);
        target_buf[sizeof(target_buf) - 1] = '\0';
    }
    trim_inplace(target_buf);

    if (starts_with_ci(target_buf, "Category:")) {
        return after; /* categories aren't shown inline, matching MediaWiki */
    }

    if (starts_with_ci(target_buf, "File:") || starts_with_ci(target_buf, "Image:")) {
        int np;
        char **params = depth_split_pipe(content, &np); /* params[0] = filename */
        char *caption = NULL;
        for (int i = np - 1; i >= 1; i--) {
            char t[512];
            strncpy(t, params[i], sizeof(t) - 1);
            t[sizeof(t) - 1] = '\0';
            trim_inplace(t);
            if (t[0] && !is_image_keyword(t)) { caption = params[i]; break; }
        }
        if (caption) {
            trim_inplace(caption);
            runlist_push(out, "[Image: ", ATTR_DIM, -1);
            int bold = 0, italic = 0;
            inline_parse(caption, doc, idx, out, &bold, &italic);
            runlist_push(out, "]", ATTR_DIM, -1);
        } else {
            runlist_push(out, "[Image]", ATTR_DIM, -1);
        }
        for (int i = 0; i < np; i++) free(params[i]);
        free(params);
        return after;
    }

    char display_buf[1024];
    if (pipe) {
        strncpy(display_buf, pipe + 1, sizeof(display_buf) - 1);
        display_buf[sizeof(display_buf) - 1] = '\0';
        trim_inplace(display_buf);
    } else {
        strncpy(display_buf, target_buf, sizeof(display_buf) - 1);
        display_buf[sizeof(display_buf) - 1] = '\0';
        for (char *c = display_buf; *c; c++) if (*c == '_') *c = ' ';
        char *hash = strchr(display_buf, '#');
        if (hash) *hash = '\0';
        trim_inplace(display_buf);
    }
    if (!display_buf[0]) {
        strncpy(display_buf, target_buf, sizeof(display_buf) - 1);
        display_buf[sizeof(display_buf) - 1] = '\0';
    }

    int found = wiki_index_resolve(idx, target_buf);
    const char *resolved_title = found >= 0 ? idx->articles[found].title : target_buf;
    int link_idx = doc_add_link(doc, display_buf, resolved_title, found >= 0, found);
    runlist_push(out, display_buf, 0, link_idx);
    return after;
}

/* Single-bracket external links, e.g. [http://... label]. Never made
 * navigable -- this app does no networking, so these are always inert
 * text, shown dimmed to signal they're not clickable. */
static const char *handle_external_link(const char *p, RunList *out) {
    p += 1; /* skip [ */
    const char *end = strchr(p, ']');
    const char *stop = end ? end : p + strlen(p);
    size_t clen = (size_t)(stop - p);
    char content[1024];
    size_t cl = clen < sizeof(content) - 1 ? clen : sizeof(content) - 1;
    memcpy(content, p, cl);
    content[cl] = '\0';
    const char *after = end ? end + 1 : stop;

    if (starts_with_ci(content, "http://") || starts_with_ci(content, "https://") ||
        starts_with_ci(content, "ftp://") || starts_with_ci(content, "mailto:")) {
        char *sp = content;
        while (*sp && !isspace((unsigned char)*sp)) sp++;
        char label[900];
        if (*sp) {
            while (isspace((unsigned char)*sp)) sp++;
            strncpy(label, sp, sizeof(label) - 1);
        } else {
            strncpy(label, content, sizeof(label) - 1);
        }
        label[sizeof(label) - 1] = '\0';
        trim_inplace(label);
        if (!label[0]) { strncpy(label, content, sizeof(label) - 1); label[sizeof(label) - 1] = '\0'; }
        runlist_push(out, label, ATTR_DIM, -1);
    } else {
        char lit[1050];
        snprintf(lit, sizeof(lit), "[%s]", content);
        runlist_push(out, lit, 0, -1);
    }
    return after;
}

static void inline_parse(const char *text, Doc *doc, const WikiIndex *idx, RunList *out, int *bold, int *italic) {
    SB buf; sb_init(&buf);
    const char *p = text;
    while (*p) {
        unsigned attr = (unsigned)((*bold ? ATTR_BOLD : 0) | (*italic ? ATTR_ITALIC : 0));

        if (p[0] == '\'' && p[1] == '\'') {
            int run = 0;
            const char *q = p;
            while (*q == '\'') { run++; q++; }
            flush_buf(&buf, out, attr);
            if (run == 2) {
                *italic = !*italic;
            } else if (run == 3) {
                *bold = !*bold;
            } else if (run == 4) {
                runlist_push(out, "'", attr, -1);
                *bold = !*bold;
            } else { /* run >= 5 */
                *bold = !*bold;
                *italic = !*italic;
                for (int i = 0; i < run - 5; i++) sb_putc(&buf, '\'');
            }
            p = q;
            continue;
        }
        if (p[0] == '[' && p[1] == '[') {
            flush_buf(&buf, out, attr);
            p = handle_internal_link(p, doc, idx, out);
            continue;
        }
        if (p[0] == '[') {
            flush_buf(&buf, out, attr);
            p = handle_external_link(p, out);
            continue;
        }
        if (starts_with_ci(p, "http://") || starts_with_ci(p, "https://")) {
            flush_buf(&buf, out, attr);
            const char *q = p;
            while (*q && !isspace((unsigned char)*q)) q++;
            char url[1024];
            size_t ul = (size_t)(q - p);
            if (ul > sizeof(url) - 1) ul = sizeof(url) - 1;
            memcpy(url, p, ul);
            url[ul] = '\0';
            runlist_push(out, url, ATTR_DIM, -1);
            p = q;
            continue;
        }

        sb_putc(&buf, *p);
        p++;
    }
    unsigned attr = (unsigned)((*bold ? ATTR_BOLD : 0) | (*italic ? ATTR_ITALIC : 0));
    flush_buf(&buf, out, attr);
    free(buf.buf);
}

/* ---------------- block-level parsing ---------------- */

static int parse_heading(Doc *doc, const char *ls, const WikiIndex *idx) {
    size_t len = strlen(ls);
    size_t end = len;
    while (end > 0 && isspace((unsigned char)ls[end - 1])) end--;
    int lead = 0;
    while (lead < (int)end && ls[lead] == '=') lead++;
    if (lead < 1) return 0;
    int trail = 0;
    while (trail < (int)end - lead && ls[end - 1 - trail] == '=') trail++;
    if (trail < 1) return 0;
    int level = lead < trail ? lead : trail;
    if (level < 1) return 0;
    if (level > 6) level = 6;
    int inner_start = lead;
    int inner_end = (int)end - trail;
    if (inner_end <= inner_start) return 0;

    char inner[2048];
    int il = inner_end - inner_start;
    if (il > (int)sizeof(inner) - 1) il = (int)sizeof(inner) - 1;
    memcpy(inner, ls + inner_start, il);
    inner[il] = '\0';
    trim_inplace(inner);
    if (!inner[0]) return 0;

    Block *b = doc_add_block(doc, BLK_HEADING);
    b->level = level;
    int bold = 0, italic = 0;
    inline_parse(inner, doc, idx, &b->text, &bold, &italic);
    return level;
}

static void parse_list_item(Doc *doc, const char *ls, const WikiIndex *idx) {
    int level = 0, ordered = 0;
    const char *p = ls;
    while (*p == '*' || *p == '#' || *p == ':' || *p == ';') {
        if (*p == '#') ordered = 1;
        level++;
        p++;
    }
    while (*p == ' ') p++;

    Block *b = doc_add_block(doc, BLK_LIST_ITEM);
    b->level = level;
    b->ordered = ordered;
    int bold = 0, italic = 0;
    inline_parse(p, doc, idx, &b->text, &bold, &italic);
}

/* Splits `s` on a 2-char delimiter (e.g. "||" or "!!"), ignoring occurrences
 * inside [[ ... ]] spans. Returns a malloc'd array of malloc'd, trimmed
 * strings; caller frees each string and the array. */
static char **depth_split(const char *s, const char *delim2, int *out_n) {
    int cap = 8, n = 0;
    char **out = malloc(cap * sizeof(char *));
    int depth = 0;
    const char *start = s;
    const char *p = s;
    while (*p) {
        if (p[0] == '[' && p[1] == '[') { depth++; p += 2; continue; }
        if (p[0] == ']' && p[1] == ']') { if (depth > 0) depth--; p += 2; continue; }
        if (depth == 0 && p[0] == delim2[0] && p[1] == delim2[1]) {
            size_t len = (size_t)(p - start);
            char *piece = malloc(len + 1);
            memcpy(piece, start, len);
            piece[len] = '\0';
            trim_inplace(piece);
            if (n == cap) { cap *= 2; out = realloc(out, cap * sizeof(char *)); }
            out[n++] = piece;
            p += 2;
            start = p;
            continue;
        }
        p++;
    }
    size_t len = (size_t)(p - start);
    char *piece = malloc(len + 1);
    memcpy(piece, start, len);
    piece[len] = '\0';
    trim_inplace(piece);
    if (n == cap) { cap *= 2; out = realloc(out, cap * sizeof(char *)); }
    out[n++] = piece;
    *out_n = n;
    return out;
}

/* Finds the first top-level '|' in a table cell/caption's raw content,
 * skipping any '|' nested inside a [[link|display]] span -- same
 * depth-tracking approach as depth_split(), just for a single delimiter
 * instead of a whole-line split. Cells and `|+` captions both use this to
 * split an optional "attrs | content" prefix from the real content, e.g.:
 *   rowspan="2" | Artifact name
 *   |+ class="nowrap" | '''Attributed caption'''
 * A piece with no top-level pipe at all has no attributes -- it's already
 * just the content. */
static const char *find_toplevel_pipe(const char *s) {
    int depth = 0;
    for (const char *p = s; *p; p++) {
        if (p[0] == '[' && p[1] == '[') { depth++; p++; continue; }
        if (p[0] == ']' && p[1] == ']') { if (depth > 0) depth--; p++; continue; }
        if (depth == 0 && *p == '|') return p;
    }
    return NULL;
}

static void table_row_add_cells(Block *row, const char *content, const char *delim2, Doc *doc, const WikiIndex *idx) {
    int n;
    char **cells = depth_split(content, delim2, &n);
    for (int c = 0; c < n; c++) {
        /* A cell can carry HTML-style attributes before its content,
         * separated by one more top-level '|', e.g.
         * `rowspan="2" | Artifact name` or `class="unsortable" | Carried`
         * (find_toplevel_pipe() is the same helper |+ table captions
         * already use for this exact "attrs | content" split, just
         * applied per-cell here instead of once for the whole caption
         * line). Most cells have no attributes at all -- no top-level
         * pipe means the whole piece is already just the content. */
        const char *cell_text = cells[c];
        const char *pipe = find_toplevel_pipe(cell_text);
        if (pipe) {
            cell_text = pipe + 1;
            while (*cell_text == ' ' || *cell_text == '\t') cell_text++;
        }
        row->cells = realloc(row->cells, (row->n_cells + 1) * sizeof(RunList));
        memset(&row->cells[row->n_cells], 0, sizeof(RunList));
        int bold = 0, italic = 0;
        inline_parse(cell_text, doc, idx, &row->cells[row->n_cells], &bold, &italic);
        row->n_cells++;
        free(cells[c]);
    }
    free(cells);
}

/* Parses a {| ... |} table starting at lines[li] (the "{|" line) through
 * the matching "|}" (or EOF). Returns the index of the line after the
 * table. */
static int parse_table_block(Doc *doc, char **lines, int n_lines, int li, const WikiIndex *idx) {
    li++;
    Block *cur_row = NULL;

    while (li < n_lines) {
        char *line = lines[li];
        char *ls = line;
        while (*ls == ' ' || *ls == '\t') ls++;

        if (starts_with(ls, "|}")) { li++; break; }
        if (starts_with(ls, "|-")) { cur_row = NULL; li++; continue; }
        if (starts_with(ls, "|+")) {
            const char *rest = ls + 2;
            const char *pipe = find_toplevel_pipe(rest);
            const char *cap = pipe ? pipe + 1 : rest;
            char capbuf[2048];
            strncpy(capbuf, cap, sizeof(capbuf) - 1);
            capbuf[sizeof(capbuf) - 1] = '\0';
            trim_inplace(capbuf);
            if (capbuf[0]) {
                Block *capb = doc_add_block(doc, BLK_TABLE_CAPTION);
                int bold = 0, italic = 0;
                inline_parse(capbuf, doc, idx, &capb->text, &bold, &italic);
            }
            li++;
            continue;
        }

        if (ls[0] == '!') {
            if (!cur_row) cur_row = doc_add_block(doc, BLK_TABLE_ROW);
            cur_row->header_row = 1;
            table_row_add_cells(cur_row, ls + 1, "!!", doc, idx);
            li++;
            continue;
        }
        if (ls[0] == '|') {
            if (!cur_row) cur_row = doc_add_block(doc, BLK_TABLE_ROW);
            table_row_add_cells(cur_row, ls + 1, "||", doc, idx);
            li++;
            continue;
        }
        li++; /* stray line (e.g. table-tag attributes on their own line) */
    }
    return li;
}

static char **split_lines(char *text, int *out_n) {
    int cap = 256, n = 0;
    char **lines = malloc(cap * sizeof(char *));
    lines[n++] = text;
    for (char *c = text; *c; c++) {
        if (*c == '\n') {
            *c = '\0';
            if (n == cap) { cap *= 2; lines = realloc(lines, cap * sizeof(char *)); }
            lines[n++] = c + 1;
        }
    }
    *out_n = n;
    return lines;
}

Doc *wikitext_parse(const char *title, const char *raw, const WikiIndex *idx) {
    Doc *doc = doc_new(title);
    char *text = preprocess(raw, idx);

    int n_lines;
    char **lines = split_lines(text, &n_lines);
    for (int i = 0; i < n_lines; i++) {
        size_t l = strlen(lines[i]);
        while (l > 0 && lines[i][l - 1] == '\r') lines[i][--l] = '\0';
    }

    Block *open_para = NULL;
    int para_bold = 0, para_italic = 0;

    int li = 0;
    while (li < n_lines) {
        char *line = lines[li];

        /* Preformatted line: MediaWiki's leading-space convention, or a
         * line marked by mark_pre_blocks() as having been inside <pre>.
         * Rendered verbatim (see BLK_PRE in doc_wrap) -- never word-wrapped
         * or joined with neighboring lines, which is what NetHackWiki's
         * ASCII dungeon maps rely on for their layout. */
        if (line[0] == ' ' || line[0] == PRE_MARK) {
            open_para = NULL;
            Block *pre = doc_add_block(doc, BLK_PRE);
            while (li < n_lines && (lines[li][0] == ' ' || lines[li][0] == PRE_MARK)) {
                pre->cells = realloc(pre->cells, (size_t)(pre->n_cells + 1) * sizeof(RunList));
                memset(&pre->cells[pre->n_cells], 0, sizeof(RunList));
                int bold = 0, italic = 0;
                inline_parse(lines[li] + 1, doc, idx, &pre->cells[pre->n_cells], &bold, &italic);
                pre->n_cells++;
                li++;
            }
            continue;
        }

        char *ls = line;
        while (*ls == ' ' || *ls == '\t') ls++;

        if (*ls == '\0') {
            open_para = NULL;
            if (doc->n_blocks > 0 && doc->blocks[doc->n_blocks - 1].type != BLK_BLANK)
                doc_add_block(doc, BLK_BLANK);
            li++;
            continue;
        }
        if (starts_with(ls, "{|")) {
            open_para = NULL;
            li = parse_table_block(doc, lines, n_lines, li, idx);
            continue;
        }
        if (ls[0] == '=') {
            open_para = NULL;
            int lvl = parse_heading(doc, ls, idx);
            if (lvl > 0) { li++; continue; }
            /* not a real heading; fall through and treat as paragraph text */
        }
        if (starts_with(ls, "----")) {
            open_para = NULL;
            doc_add_block(doc, BLK_HR);
            li++;
            continue;
        }
        if (ls[0] == '*' || ls[0] == '#' || ls[0] == ':' || ls[0] == ';') {
            open_para = NULL;
            parse_list_item(doc, ls, idx);
            li++;
            continue;
        }

        if (!open_para) {
            open_para = doc_add_block(doc, BLK_PARAGRAPH);
            para_bold = 0;
            para_italic = 0;
        } else {
            runlist_push(&open_para->text, " ", 0, -1);
        }
        inline_parse(ls, doc, idx, &open_para->text, &para_bold, &para_italic);
        li++;
    }

    free(lines);
    free(text);
    return doc;
}
